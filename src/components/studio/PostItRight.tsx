"use client";

import { useCallback, useSyncExternalStore } from "react";

/*
 * The "Post it right" checklist shown with every finished video. The steps are TikTok's
 * own posting flow (More options → AI-generated content; Content disclosure and
 * settings), written out because screenshots date faster than words.
 */

const STEPS = [
  {
    key: "ai-label",
    title: "Turn on TikTok's AI-generated content label",
    body: "When you post, open More options and switch on AI-generated content. TikTok shows a small \"Creator labeled as AI-generated\" line under the video. TikTok requires this label on realistic AI video; unlabeled posts can be removed or restricted, and a label TikTok adds itself can't be taken off.",
  },
  {
    key: "commercial",
    title: "Turn on the commercial content disclosure",
    body: "In the same More options sheet, open Content disclosure and settings and choose Your brand, since the video sells your own product. Product videos without the disclosure may not be eligible for the For You feed; TikTok gives 24 hours to fix it.",
  },
  {
    key: "caption",
    title: "Say it in the caption and add your shop link",
    body: "A short line such as \"AI presenter, real product\" keeps viewers oriented. Then attach the product so the video carries the shop link.",
  },
  {
    key: "claims",
    title: "Keep the caption to the same standard as the script",
    body: "No \"real customer\" claims, no before/after promises, no health or weight-loss results. The presenter is a fictional brand host describing product facts; your caption should be too.",
  },
] as const;

type Key = (typeof STEPS)[number]["key"];

const NONE: Record<Key, boolean> = { "ai-label": false, commercial: false, caption: false, claims: false };

function storageKey(jobId: string) {
  return `wm_post_${jobId}`;
}

/*
 * The ticks live in localStorage and reach React through useSyncExternalStore: the server
 * snapshot is "nothing ticked", the client snapshot is the stored string (a stable
 * primitive), so there is no effect and no hydration mismatch.
 */
const listeners = new Set<() => void>();
function subscribe(l: () => void) {
  listeners.add(l);
  window.addEventListener("storage", l);
  return () => {
    listeners.delete(l);
    window.removeEventListener("storage", l);
  };
}
function readRaw(key: string): string {
  try {
    return localStorage.getItem(key) ?? "";
  } catch {
    return "";
  }
}
function parseFlags(raw: string): Record<Key, boolean> {
  if (!raw) return NONE;
  try {
    const v = JSON.parse(raw) as Partial<Record<Key, boolean>>;
    return { ...NONE, ...v };
  } catch {
    return NONE;
  }
}

export function PostItRight({ jobId }: { jobId: string }) {
  const key = storageKey(jobId);
  const raw = useSyncExternalStore(
    subscribe,
    () => readRaw(key),
    () => "",
  );
  const done = parseFlags(raw);

  const toggle = useCallback(
    (k: Key) => {
      const next = { ...parseFlags(readRaw(key)), [k]: !parseFlags(readRaw(key))[k] };
      try {
        localStorage.setItem(key, JSON.stringify(next));
      } catch {
        /* private mode: the tick is lost on reload, nothing else breaks */
      }
      for (const l of listeners) l();
    },
    [key],
  );

  const remaining = STEPS.filter((s) => !done[s.key]).length;

  return (
    <section className="pane p-5 sm:p-6" aria-labelledby="post-it-right">
      <div className="flex items-start justify-between gap-3">
        <div>
          <p className="eyebrow">Post it right</p>
          <h2 id="post-it-right" className="headline mt-1.5 text-[1.3rem] text-ink">
            Two switches TikTok expects on every AI product video
          </h2>
        </div>
        <span className={`tag ${remaining === 0 ? "tag-ok" : ""}`}>{remaining === 0 ? "All set" : `${remaining} left`}</span>
      </div>
      <ol className="mt-5 space-y-2.5">
        {STEPS.map((s, i) => (
          <li key={s.key}>
            <label className={`flex cursor-pointer gap-3 rounded-[20px] px-4 py-3.5 transition-colors ${done[s.key] ? "bg-ok-soft" : "bg-pane-2"}`}>
              <input type="checkbox" checked={done[s.key]} onChange={() => toggle(s.key)} className="mt-1 h-5 w-5 shrink-0 accent-[var(--accent)]" />
              <span className="min-w-0">
                <span className="block text-[0.98rem] font-semibold text-ink">
                  {i + 1}. {s.title}
                </span>
                <span className="mt-1 block text-[0.88rem] leading-relaxed text-ink-3">{s.body}</span>
              </span>
            </label>
          </li>
        ))}
      </ol>
      <p className="mt-4 text-[0.82rem] leading-relaxed text-ink-4">
        This video was generated by AI from your photos. Keeping both switches on is your responsibility as the poster; WindowMuse never removes or hides AI labels from an export.
      </p>
    </section>
  );
}
